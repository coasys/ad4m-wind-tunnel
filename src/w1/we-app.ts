/**
 * W1 helper: build and serve the WE web app (apps/we-web) against a given executor.
 *
 * WE is built with its own Vite config, wrapped by a generated config that only
 *  - points `@coasys/ad4m` / `@coasys/ad4m-connect` at the ad4m checkout the executor was built
 *    from (`sdk: "executor"`), or leaves WE's pinned SDK alone (`sdk: "pinned"`);
 *  - writes the build into a temp dir and serves it on a chosen port.
 * Nothing in the WE checkout is modified: no package.json override, no lockfile change.
 *
 * `mode: "preview"` is a production build served by `vite preview` (closest to what a user loads);
 * `mode: "dev"` runs the Vite dev server (unbundled ESM, dev-only code paths, HMR socket).
 */

import { spawn, ChildProcess, execSync } from "child_process";
import { createHash } from "crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

export interface WeAppOptions {
  /** Root of the WE monorepo checkout (packages already built: `pnpm install && pnpm build:web`). */
  weRepo: string;
  /** "executor" aliases the SDK to `ad4mRepo`'s core/connect builds; "pinned" uses WE's own. */
  sdk: "executor" | "pinned";
  /** ad4m checkout whose `core/lib` and `connect/dist` are built. Required for sdk=executor. */
  ad4mRepo?: string;
  mode: "preview" | "dev";
  port: number;
  /** Scratch dir for the wrapper config, Vite cache and build output. */
  workDir: string;
  /** Rebuild even if a build for the same inputs exists. */
  rebuild?: boolean;
  log?: (line: string) => void;
}

export interface WeApp {
  url: string;
  /** Version prefix ad4m-connect writes its localStorage keys under (`<version>/ad4m-token`). */
  connectVersion: string;
  /** Version of `@coasys/ad4m` the app was built with. */
  sdkVersion: string;
  /** Where the SDK came from (path), for the report. */
  sdkSource: string;
  weCommit: string;
  buildMs: number;
  stop(): Promise<void>;
}

function gitHead(dir: string): string {
  try {
    return execSync("git rev-parse --short HEAD", { cwd: dir, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "unknown";
  }
}

function gitDirty(dir: string): boolean {
  try {
    return execSync("git status --porcelain --untracked-files=no", { cwd: dir, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim().length > 0;
  } catch {
    return false;
  }
}

function readVersion(pkgJson: string): string {
  return JSON.parse(readFileSync(pkgJson, "utf8")).version as string;
}

/** Environment for WE tooling: the shell's NODE_ENV=production breaks WE dev builds. */
function weEnv(): NodeJS.ProcessEnv {
  const env = { ...process.env };
  delete env.NODE_ENV;
  return env;
}

function sdkPaths(opts: WeAppOptions) {
  const appDir = join(opts.weRepo, "apps", "we-web");
  if (opts.sdk === "pinned") {
    const core = join(appDir, "node_modules", "@coasys", "ad4m");
    const connect = join(appDir, "node_modules", "@coasys", "ad4m-connect");
    return { core, connect, alias: false };
  }
  if (!opts.ad4mRepo) throw new Error("w1: sdk=executor needs the ad4m repo (--ad4m-repo / AD4M_REPO / W1_AD4M_SDK_REPO)");
  const core = join(opts.ad4mRepo, "core");
  const connect = join(opts.ad4mRepo, "connect");
  for (const required of [join(core, "lib", "index.js"), join(connect, "dist", "index.js")]) {
    if (!existsSync(required)) {
      throw new Error(
        `w1: ${required} is missing — build the SDK first (cd ${opts.ad4mRepo} && pnpm install && ` +
          `(cd core && pnpm run build) && (cd connect && pnpm run build))`,
      );
    }
  }
  return { core, connect, alias: true };
}

/** The wrapper config: WE's own config, plus SDK aliases, a private cache dir and output dir. */
function writeWrapperConfig(opts: WeAppOptions, outDir: string, cacheDir: string): string {
  const appDir = join(opts.weRepo, "apps", "we-web");
  const sdk = sdkPaths(opts);
  const aliases = sdk.alias
    ? [
        { find: "^@coasys/ad4m$", replacement: join(sdk.core, "lib", "index.js") },
        { find: "^@coasys/ad4m-connect$", replacement: join(sdk.connect, "dist", "index.js") },
        { find: "^@coasys/ad4m-connect/(.*)$", replacement: join(sdk.connect, "dist", "$1.js") },
      ]
    : [];
  const configPath = join(opts.workDir, "vite.w1.config.mjs");
  const source = `// Generated by ad4m-wind-tunnel w1 — wraps WE's own Vite config. Do not edit.
import base from ${JSON.stringify(join(appDir, "vite.config.ts"))};

const sdkAliases = ${JSON.stringify(aliases)}.map((a) => ({ find: new RegExp(a.find), replacement: a.replacement }));
const baseAlias = base.resolve?.alias ?? {};
const baseAliasList = Array.isArray(baseAlias)
  ? baseAlias
  : Object.entries(baseAlias).map(([find, replacement]) => ({ find, replacement }));

export default {
  ...base,
  root: ${JSON.stringify(appDir)},
  cacheDir: ${JSON.stringify(cacheDir)},
  resolve: { ...(base.resolve ?? {}), alias: [...sdkAliases, ...baseAliasList] },
  build: { ...(base.build ?? {}), outDir: ${JSON.stringify(outDir)}, emptyOutDir: true },
  server: { ...(base.server ?? {}), host: "127.0.0.1", port: ${opts.port}, strictPort: true, hmr: { port: ${opts.port + 1} } },
  preview: { host: "127.0.0.1", port: ${opts.port}, strictPort: true },
};
`;
  writeFileSync(configPath, source);
  return configPath;
}

function viteBin(weRepo: string): string {
  const bin = join(weRepo, "apps", "we-web", "node_modules", "vite", "bin", "vite.js");
  if (!existsSync(bin)) {
    throw new Error(`w1: ${bin} not found — run \`unset NODE_ENV; pnpm install && pnpm build:web\` in ${weRepo}`);
  }
  return bin;
}

async function waitForHttp(url: string, timeoutMs: number, proc: ChildProcess): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (proc.exitCode !== null) throw new Error(`w1: WE server exited early (code ${proc.exitCode})`);
    try {
      const res = await fetch(url);
      if (res.ok) return;
    } catch {}
    await new Promise((r) => setTimeout(r, 300));
  }
  throw new Error(`w1: WE server at ${url} did not answer within ${timeoutMs}ms`);
}

export async function startWeApp(opts: WeAppOptions): Promise<WeApp> {
  const log = opts.log ?? ((l: string) => console.log(`[w1:we] ${l}`));
  const appDir = join(opts.weRepo, "apps", "we-web");
  if (!existsSync(join(appDir, "vite.config.ts"))) throw new Error(`w1: no WE web app at ${appDir} (set --we-repo / WE_REPO)`);
  const sdk = sdkPaths(opts);
  const sdkVersion = readVersion(join(sdk.core, "package.json"));
  const connectVersion = readVersion(join(sdk.connect, "package.json"));
  const weCommit = gitHead(opts.weRepo) + (gitDirty(opts.weRepo) ? "-dirty" : "");
  const sdkCommit = opts.sdk === "executor" ? gitHead(opts.ad4mRepo!) : "pinned";

  mkdirSync(opts.workDir, { recursive: true });
  // One build per (WE commit, SDK source) — a WE rebuild takes a while and the inputs rarely move.
  const key = createHash("sha1").update(`${weCommit}|${opts.sdk}|${sdk.core}|${sdkCommit}|${sdkVersion}`).digest("hex").slice(0, 12);
  const outDir = join(opts.workDir, `dist-${key}`);
  const cacheDir = join(opts.workDir, `vite-cache-${key}`);
  const config = writeWrapperConfig(opts, outDir, cacheDir);
  const vite = viteBin(opts.weRepo);

  let buildMs = 0;
  if (opts.mode === "preview" && (opts.rebuild || !existsSync(join(outDir, "index.html")) || weCommit.endsWith("-dirty"))) {
    log(`building WE ${weCommit} (production, sdk=${opts.sdk} ${sdkVersion}) → ${outDir}`);
    const t0 = Date.now();
    execSync(`node "${vite}" build --config "${config}" --logLevel warn`, {
      cwd: appDir,
      env: weEnv(),
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 900_000,
      maxBuffer: 64 * 1024 * 1024,
    });
    buildMs = Date.now() - t0;
    log(`built in ${(buildMs / 1000).toFixed(1)}s`);
  } else if (opts.mode === "preview") {
    log(`reusing WE build ${outDir}`);
  }

  const args = opts.mode === "preview" ? [vite, "preview", "--config", config] : [vite, "--config", config];
  const proc = spawn("node", args, { cwd: appDir, env: weEnv(), stdio: ["ignore", "pipe", "pipe"] });
  const output: string[] = [];
  proc.stdout?.on("data", (d) => output.push(String(d)));
  proc.stderr?.on("data", (d) => output.push(String(d)));
  const url = `http://127.0.0.1:${opts.port}`;
  try {
    await waitForHttp(url, opts.mode === "dev" ? 180_000 : 60_000, proc);
  } catch (err) {
    proc.kill("SIGTERM");
    throw new Error(`${(err as Error).message}\n${output.join("").slice(-4000)}`);
  }
  log(`serving at ${url} (${opts.mode})`);

  return {
    url,
    connectVersion,
    sdkVersion,
    sdkSource: opts.sdk === "executor" ? `${opts.ad4mRepo}@${sdkCommit}` : `WE pin (${sdk.core})`,
    weCommit,
    buildMs,
    async stop() {
      if (proc.exitCode !== null) return;
      proc.kill("SIGTERM");
      await new Promise<void>((resolve) => {
        const timer = setTimeout(() => {
          if (proc.exitCode === null) proc.kill("SIGKILL");
          resolve();
        }, 5000);
        proc.once("exit", () => {
          clearTimeout(timer);
          resolve();
        });
      });
    },
  };
}
